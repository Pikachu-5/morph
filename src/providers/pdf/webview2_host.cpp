// The WebView2 host (architecture section 8.6, "practical notes").
//
// "Run the WebView2 host in a dedicated worker with a hidden window, because a
//  WebView2 needs an HWND and a message pump. Reuse one environment across jobs
//  -- creating the environment is the expensive part, roughly 200-400 ms, while
//  navigation is fast."
//
// So: one thread, one message-only window, one environment, created lazily on
// first use and kept alive for the process. Requests are serialised through it,
// which is also what section 11.1 asks for ("PDF render (WebView2): concurrency
// 1. One WebView2 environment, reused. Serialise through it").
//
// EVERYTHING HERE IS ASYNCHRONOUS. WebView2 delivers navigation and printing
// results as callbacks on the pump, so a request is a small state machine:
// navigate -> NavigationCompleted -> PrintToPdfStream -> drain -> signal. The
// message handler must never block, or the callbacks it is waiting for can never
// arrive.
//
// SECURITY (section 15.1). The HTML fed to WebView2 is generated by OUR writer
// from the IR, never passed through from user input. Even so, this host disables
// the network stack through command-line switches and cancels every navigation
// whose scheme is not data:, file: or about:. A document that finds a way to
// reference an external resource gets nothing.

